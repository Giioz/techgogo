export function getLocalizedService(service: Service, lang: string): Service {
  const isKa = lang === "ka";
  return {
    ...service,
    title: isKa ? service.title : (service.titleEn || service.title),
    shortDesc: isKa ? service.shortDesc : (service.shortDescEn || service.shortDesc),
    fullDesc: isKa ? service.fullDesc : (service.fullDescEn || service.fullDesc),
    clientImpact: isKa ? service.clientImpact : (service.clientImpactEn || service.clientImpact),
    deliverables: isKa ? service.deliverables : (service.deliverablesEn || service.deliverables),
    checklistItems: isKa ? service.checklistItems : (service.checklistItemsEn || service.checklistItems),
    processSteps: service.processSteps.map((s) => ({
      ...s,
      title: isKa ? s.title : (s.titleEn || s.title),
      description: isKa ? s.description : (s.descriptionEn || s.description),
    })),
  };
}
