export function getLocalizedCourse(course: Course, lang: string): Course {
  const isKa = lang === "ka";
  return {
    ...course,
    title: isKa ? course.title : (course.titleEn || course.title),
    category: isKa ? course.category : (course.categoryEn || course.category),
    duration: isKa ? course.duration : (course.durationEn || course.duration),
    price: isKa ? course.price : (course.priceEn || (course.isFree ? "Free" : course.price)),
    originalPrice: isKa ? course.originalPrice : (course.originalPriceEn || course.originalPrice),
    badge: isKa ? course.badge : (course.badgeEn || course.badge),
    description: isKa ? course.description : (course.descriptionEn || course.description),
    format: isKa
      ? (course.format === "Remote" ? "დისტანციური" : course.format === "Hybrid" ? "ჰიბრიდული" : course.format)
      : (course.format === "დისტანციური" ? "Remote" : course.format === "ჰიბრიდული" ? "Hybrid" : course.format),
    instructor: {
      ...course.instructor,
      name: isKa ? course.instructor.name : (course.instructor.nameEn || course.instructor.name),
      role: isKa ? course.instructor.role : (course.instructor.roleEn || course.instructor.role),
      bio: isKa ? course.instructor.bio : (course.instructor.bioEn || course.instructor.bio),
    },
    whatYouWillLearn: isKa ? course.whatYouWillLearn : (course.whatYouWillLearnEn || course.whatYouWillLearn),
    curriculum: course.curriculum?.map((m) => ({
      ...m,
      title: isKa ? m.title : (m.titleEn || m.title),
      topics: isKa ? m.topics : (m.topicsEn || m.topics),
    })),
    outcomes: isKa ? course.outcomes : (course.outcomesEn || course.outcomes),
    targetAudience: isKa ? course.targetAudience : (course.targetAudienceEn || course.targetAudience),
  };
}
